// ─── Mock stream ──────────────────────────────────────────────────────────────

function createMockStream(responseText) {
  const listeners = {};

  const stream = {
    on: jest.fn((event, handler) => {
      listeners[event] = handler;
      return stream;
    }),

    finalMessage: jest.fn(() => {
      // Emit text event with the response
      if (listeners['text']) {
        listeners['text'](responseText);
      }
      return Promise.resolve({
        id: 'msg_mock',
        type: 'message',
        role: 'assistant',
        content: [{ type: 'text', text: responseText }],
        model: 'claude-opus-4-6',
        stop_reason: 'end_turn',
        stop_sequence: null,
        usage: { input_tokens: 800, output_tokens: 1200 },
      });
    }),
  };

  return stream;
}

// ─── Mock error stream ────────────────────────────────────────────────────────

function createErrorStream(errorMessage) {
  return {
    on: jest.fn().mockReturnThis(),
    finalMessage: jest.fn().mockRejectedValue(new Error(errorMessage)),
  };
}

